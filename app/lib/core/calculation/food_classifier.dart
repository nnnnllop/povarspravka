  /// Слова названия: нижний регистр, «ё» → «е», разделители — всё, кроме
  /// букв и цифр. Сложное прилагательное через дефис («шоколадно-миндальный»,
  /// «варено-копченая») остаётся одним словом, остальные слова через дефис
  /// разделяются («жир-сырец» → «жир», «сырец»; «какао-порошок» → «какао»,
  /// «порошок»).
  static List<String> tokenize(String name) {
    final lower = name.toLowerCase().replaceAll('ё', 'е');
    final tokens = <String>[];
    for (final chunk in lower.split(_separator)) {
      final parts = chunk.split('-').where((p) => p.isNotEmpty).toList();
      if (parts.isEmpty) continue;
      final compoundAdjective = parts.length > 1 &&
          _isAdjective(parts.last) &&
          parts
              .sublist(0, parts.length - 1)
              .every((p) => p.endsWith('о') || p.endsWith('е'));
      if (compoundAdjective) {
        tokens.add(parts.join('-'));
      } else {
        tokens.addAll(parts);
      }
    }
    return List.unmodifiable(tokens);
  }

  static final RegExp _separator = RegExp('[^a-zа-я0-9-]+');

  /// Позиция главного слова названия: первое слово, если это не
  /// прилагательное, иначе слово после одного-двух ведущих прилагательных
  /// («Шоколадный торт» → «торт», «Ржаная хлебная крупка» → «крупка»).
  static int headIndex(List<String> tokens) {
    var i = 0;
    var skipped = 0;
    while (skipped < 3 &&
        i < tokens.length - 1 &&
        !_beforePreposition(tokens, i) &&
        (_isAdjective(tokens[i]) || tokens[i] == 'и')) {
      i++;
      skipped++;
    }
    // «Макаронные изделия», «Изделия макаронные»: общее слово — главным
    // считается прилагательное рядом.
    if (_genericHeads.contains(tokens[i])) {
      if (i > 0) return i - 1;
      if (tokens.length > 1) return 1;
    }
    return i;
  }

  /// Слово перед предлогом — главное («Тушёный цикорий под соусом»).
  static bool _beforePreposition(List<String> tokens, int i) {
    final next = tokens[i + 1];
    return next != 'и' && _prepositions.contains(next);
  }

  static const Set<String> _genericHeads = {
    'изделия', 'изделие', 'изделий', 'продукт', 'продукты', 'смесь', //
    'полуфабрикат', 'полуфабрикаты', 'консервы', 'концентрат',
  };

  static bool _isAdjective(String token) =>
      token.length > 3 &&
      !_nounsWithAdjectiveEnding.contains(token) &&
      _adjectiveEndings.any(token.endsWith);

  /// Существительные с окончанием прилагательного («Пирожное миндальное»).
  static const Set<String> _nounsWithAdjectiveEnding = {
    'пирожное', 'пирожные', 'мороженое', 'жаркое', 'заливное', //
    'сладкое', 'первое', 'второе', 'столовая', 'столовые', //
    'печенье', 'печенья', 'варенье', 'варенья', 'соленье', 'соленья', //
    'кушанье', 'настой', 'цикорий',
  };

  static const List<String> _adjectiveEndings = [
    'ый', 'ий', 'ой', 'ая', 'яя', 'ое', 'ее', 'ые', 'ие', 'ья', 'ье', 'ьи', //
  ];
}

/// Правило уточнения: слово названия совпадает со словом из [words] целиком
/// или начинается с основы из [stems].
class _Rule {
  const _Rule(
    this.group, {
    this.words = const {},
    this.stems = const [],
    this.head = false,
    this.rootOfHerb = false,
    this.requireStems = const [],
    this.excludeStems = const [],
  });

  /// Правило срабатывает, только если в названии есть слово с одной из этих основ.
  final List<String> requireStems;

  /// Правило не срабатывает, если в названии есть слово с одной из этих основ
  /// («Ботва репы» — зелень, не корнеплод).
  final List<String> excludeStems;

  final LossGroup group;
  final Set<String> words;
  final List<String> stems;

  /// Только главное слово названия: первое слово или слово после одного-двух
  /// прилагательных («Жир говяжий», «Говяжий жир», «Сливочное масло»). Слово
  /// в пояснении не считается: «… жареная без жира», «Телятина, видимый жир
  /// не более 15 %», «Салями с пониженным содержанием жира» — мясо.
  final bool head;

  /// Сельдерей и петрушка — корнеплод только со словом «корень»
  /// («Сельдерей корневой», «Петрушка (корень)»); зелень — овощ.
  final bool rootOfHerb;

  bool matchesToken(String token) {
    if (token.contains('-')) {
      return token.split('-').any(matchesToken);
    }
    if (words.contains(token)) return true;
    for (final stem in stems) {
      if (token.startsWith(stem)) return true;
    }
    return false;
  }

  bool matches(List<String> tokens) {
    bool hasStem(List<String> stems) =>
        tokens.any((t) => stems.any((s) => t.startsWith(s)));
    if (excludeStems.isNotEmpty && hasStem(excludeStems)) return false;
    if (requireStems.isNotEmpty && !hasStem(requireStems)) return false;
    if (head) {
      if (tokens.isNotEmpty &&
          matchesToken(tokens[FoodClassifier.headIndex(tokens)])) {
        return true;
      }
    } else {
      for (final token in tokens) {
        if (matchesToken(token)) return true;
      }
    }
    if (rootOfHerb) {
      final herb =
          tokens.any((t) => t.startsWith('сельдер') || t.startsWith('петруш'));
      final root = tokens.any((t) => t.startsWith('корн') || t == 'корень');
      if (herb && root) return true;
    }
    return false;
  }
}
