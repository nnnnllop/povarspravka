  /// Группа по названию (продукт без группы справочника или готовое блюдо
  /// BLS X/Y). Решает **главное слово** названия ([headIndex]):
  ///
  /// 1. Составное блюдо («Суп …», «Рагу …», «Соус …», «Блюдо из …»,
  ///    «Пудинг …») — [LossGroup.other]: средние потери смеси.
  /// 2. Жир или масло («Лимонное масло», «Жир говяжий») — [LossGroup.fatOil].
  /// 3. Главное слово из словаря («Говяжий язык отварной» → мясо,
  ///    «Брюква тушёная в светлом соусе» → корнеплоды).
  /// 4. Форма без сырья («Стейк», «Филе», «Котлета», «Салат», «Пюре»,
  ///    «Мясо», «Икра») или неизвестное слово — сырьё берётся из
  ///    определений главного слова ([_modifierTokens]): «Телячий стейк» →
  ///    мясо, «Стейк из баранины» → мясо, «Котлеты из капусты» →
  ///    овощи, «Икра кабачковая» → овощи. Гарнир и соус после «с»,
  ///    «под», «в», «на» не учитываются («Куриное филе с тушёными
  ///    огурцами» → птица). Нет сырья — группа самой формы, если она
  ///    есть в словаре («Котлета» → мясо).
  /// 5. Ничего не найдено — [LossGroup.other].
  ///
  /// Мясо с птичьим словом в главном слове или определениях — птица
  /// («Колбаса из индейки»).
  static LossGroup classifyByName(String name) {
    final tokens = tokenize(name);
    if (tokens.isEmpty) return LossGroup.other;
    for (final (first, second, group) in _phrases) {
      for (var i = 0; i + 1 < tokens.length; i++) {
        if (tokens[i].startsWith(first) && tokens[i + 1].startsWith(second)) {
          return group;
        }
      }
    }
    final head = headIndex(tokens);
    final headToken = tokens[head];
    if (_compositeHeads.matchesToken(headToken)) return LossGroup.other;
    if (_fatHead.matchesToken(headToken)) return LossGroup.fatOil;
    final modifiers = _modifierTokens(tokens, head);
    final scope = [headToken, ...modifiers];
    final isForm = _formHeads.matchesToken(headToken);
    if (!isForm) {
      final byHead = _groupOfToken(headToken, scope);
      if (byHead != null) return byHead;
    }
    bool isFlavor(String t) => _flavorStems.any(t.startsWith);
    for (final token in modifiers.where((t) => !isFlavor(t))) {
      final byModifier = _groupOfToken(token, scope);
      if (byModifier != null) return byModifier;
    }
    if (isForm) {
      final byForm = _groupOfToken(headToken, scope);
      if (byForm != null) return byForm;
    }
    for (final token in modifiers.where(isFlavor)) {
      final byFlavor = _groupOfToken(token, scope);
      if (byFlavor != null) return byFlavor;
    }
    return LossGroup.other;
  }

  /// Устойчивые сочетания из двух слов (основы): «Морской язык» — рыба,
  /// а не субпродукт.
  static const List<(String, String, LossGroup)> _phrases = [
    ('морск', 'язык', LossGroup.fish),
    ('морск', 'черт', LossGroup.fish),
  ];

  /// Прилагательные-добавки («яичная паста», «медовые оладьи»): сырьём
  /// считаются, только если больше ничего не нашлось («Яичный порошок»).
  static const List<String> _flavorStems = ['яичн', 'медов', 'сахарн'];

  /// Группа одного слова по словарям [_byNameRules] (`null` — слова нет
  /// в словарях). Мясо с птичьим словом в [scope] — птица.
  static LossGroup? _groupOfToken(String token, List<String> scope) {
    for (final rule in _byNameRules) {
      if (!rule.matchesToken(token)) continue;
      if (rule.group == LossGroup.meat && _poultry.matches(scope)) {
        return LossGroup.poultry;
      }
      return rule.group;
    }
    return null;
  }

  /// Определения главного слова: слова перед ним и слова после него
  /// до первого предлога ([_prepositions]); «из» пропускается («Стейк из
  /// баранины»).
  static List<String> _modifierTokens(List<String> tokens, int head) {
    final out = [
      for (final t in tokens.sublist(0, head))
        if (!_prepositions.contains(t)) t,
    ];
    for (var i = head + 1; i < tokens.length; i++) {
      final t = tokens[i];
      if (t == 'из' || t == 'изо') continue;
      if (_prepositions.contains(t)) break;
      out.add(t);
    }
    return out;
  }

  /// Предлоги и союзы, после которых идут гарнир, соус или пояснение.
  static const Set<String> _prepositions = {
    'с', 'со', 'под', 'в', 'во', 'на', 'и', 'или', 'для', 'без', 'по', //
    'к', 'ко', 'от', 'до', 'при', 'а', 'вместо', 'после', 'типа',
  };

