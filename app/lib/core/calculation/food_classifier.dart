/// Классификация продукта по группе таблицы потерь ([LossGroup]).
///
/// **Основа — `group_id` из `reference.db`.** В справочнике 32 группы
/// (12 групп Скурихина `1…12` и 20 групп BLS `101…120`); каждой сопоставлена
/// базовая группа таблицы потерь ([baseGroupById]).
///
/// Название продукта используется **только как уточнение внутри группы
/// справочника** и **только по границам слов**: название режется на слова
/// ([tokenize]), слово сравнивается целиком ([_Rule.words]) или по началу
/// ([_Rule.stems]). Подстрока внутри слова не ищется, поэтому «сырая» не
/// «сыр», «Инжир» не «жир», «Свинина жирная» не «жир» (дефект аудита
/// 2026-10-30: подстрочный `classifyProduct` относил 505 продуктов к
/// молочным по «сыр» в «сырой/сырая»).
///
/// Группа, которой нет в справочнике (продукт собран вручную, `group_id`
/// = 0), определяется по названию ([classifyByName]) по тем же словарям.
///
/// Повар может сменить группу у ингредиента вручную
/// (`Ingredient.groupOverride`) — классификатор даёт только значение по
/// умолчанию.
abstract final class FoodClassifier {
  /// Группа таблицы потерь для продукта справочника.
  static LossGroup classify(Product product) =>
      classifyRaw(product.groupId, product.name);

  /// То же по `group_id` и названию.
  static LossGroup classifyRaw(int groupId, String name) {
    final base = baseGroupById[groupId];
    if (base == null || _dishGroupIds.contains(groupId)) {
      return classifyByName(name);
    }
    final rules = _refinements[groupId];
    if (rules == null) return base;
    final tokens = tokenize(name);
    for (final rule in rules) {
      if (rule.matches(tokens)) return rule.group;
    }
    return base;
  }

