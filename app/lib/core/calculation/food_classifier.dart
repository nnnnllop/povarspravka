  static const _formHeads = _Rule(
    LossGroup.other,
    words: {'мясо', 'мяса', 'дип', 'паста', 'пасты'},
    stems: [
      'филе', 'стейк', 'медальон', 'отбивн', 'рулет', 'рулад', 'салат', //
