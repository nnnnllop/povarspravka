def fix_measure_list(product: dict) -> bool:
    """Привести меры продукта к канону: подписи, штучные варианты, дубли."""
    code = product["code"]
    changed = False
    raw = product.get("measures") or []
    out: list[dict] = []
    seen: set[str] = set()
    pieces: list[dict] = []
    for m in raw:
        name = _measure_name(m["name"])
        if name == "1 шт." or name.startswith("1 шт. ("):
            pieces.append({"name": name, "grams": m["grams"]})
            continue
        if name in seen:
            continue
        seen.add(name)
        item = dict(m)
        item["name"] = name
        out.append(item)
        if name != m["name"]:
            changed = True
    # штучные меры: нештучным продуктам они не нужны вовсе
    if _is_no_piece_product(product) or RECIPE_NO.search(product["name"]):
        if pieces:
            changed = True
        pieces = []
    elif pieces:
        grams = sorted({float(p["grams"]) for p in pieces})
        # Если в приложении закреплён канонический штучный вес
        # (`piece_g`, из `BASE_PIECES`), он и должен остаться единственной
        # мерой «1 шт.»: иначе повторный прогон добавлял в конфеты меру из
        # предыдущего прохода и получались ложные размеры «мелкий/средний/
        # крупный» у конфет.
        canonical = product.get("piece_g") or []
        if len(canonical) == 1:
            grams = [float(canonical[0])]
        if len(grams) == 1:
            keep = [{"name": pieces[0]["name"], "grams": grams[0]}]
        else:
            # несколько размеров: подписываем «мелкий / средний / крупный»,
            # чтобы не нарушать UNIQUE(product_id, name)
            labels = list(PIECE_LABELS[:len(grams)])
            if len(grams) > len(PIECE_LABELS):
                labels = [f"{PIECE_LABELS[1]} {i}" for i in range(len(grams))]
            keep = [{"name": lab, "grams": g}
                    for lab, g in zip(labels, grams)]
        if [ (p["name"], p["grams"]) for p in pieces ] != \
                [ (p["name"], p["grams"]) for p in keep ]:
            changed = True
        pieces = keep
    out.extend(pieces)
    if out != raw:
        product["measures"] = out
        changed = True
    if code in NON_PIECE_CODES and product.get("piece_g"):
        product["piece_g"] = []
        changed = True
    return changed


def clean_values(product: dict) -> bool:
    """Убрать «шум» округления и проверить единицы витамина A (L2, C2, M4).

    * значения < 0.005 не пишем в `nutrient_value` (в UI иначе появляется
      строка «0,00 мг»);
    * `VITA_RAE ≈ RETOL + CARTB / 6` — все три поля в мкг; если RETOL или
      CARTB попали в мг, они на порядок больше РЭ и масштабируются.
    """
    changed = False
    values = _values(product)
    drop = DROP_RAE_CODES.get(product["code"])
    if drop and _values(product).get("vitamin_a_re") is not None \
            and not product.get("rae_dropped"):
        cell = product["nutrients"].get("vitamin_a_re")
        if cell is not None:
            cell["value"] = None
        product["rae_dropped"] = True
        product.setdefault("notes", []).append(f"РЭ снята: {drop}")
        changed = True
        values = _values(product)
    # РЭ без источника: если ретинол и каротин нулевые, то РЭ — «хвост»
    # пересчёта (0,2…1 мкг), и в карточке появляется строка «A 1 мкг».
    # Настоящий РЭ без обоих источников невозможен (дефект C4).
    if not product.get("rae_dropped"):
        rae0 = values.get("vitamin_a_re")
        if rae0 is not None and 0 < float(rae0) <= 1.0 \
                and not (values.get("vitamin_a") or 0) \
                and not (values.get("beta_carotene") or 0):
            cell = product["nutrients"].get("vitamin_a_re")
            if cell is not None:
                cell["value"] = None
            product["rae_dropped"] = True
            product.setdefault("notes", []).append(
                f"РЭ {float(rae0):g} мкг снята: нет ни ретинола, ни каротина")
            changed = True
            values = _values(product)
    for key, value in list(values.items()):
        if value is None:
            continue
        if abs(float(value)) < 0.005 and float(value) != 0.0:
            _set(product, key, 0.0)
            changed = True
        elif isinstance(value, float) and round(value, 3) != value:
            rounded = round(value, 3)
            _set(product, key, rounded)
            if rounded != value:
                changed = True
    # витамин A: единицы
    rae = values.get("vitamin_a_re")
    ret = values.get("vitamin_a")
    car = values.get("beta_carotene")
    if rae is not None and float(rae) > 0:
        expected = (float(ret or 0) + float(car or 0) / 6.0)
        # если РЭ в мкг, а сумма — в десятки раз больше, значит одно из
        # слагаемых записано в мг
        for key in ("vitamin_a", "beta_carotene"):
            got = values.get(key)
            if got is None or float(got) == 0:
                continue
            other = (float(values.get("vitamin_a") or 0)
                     + float(values.get("beta_carotene") or 0) / 6.0)
            if float(got) > 0 and abs(other - float(rae)) > max(
                    1.0, 0.5 * float(rae)) and float(got) / 1000.0 > 0:
                scaled = float(got) / 1000.0
                trial = other - float(got) + scaled
                if abs(trial - float(rae)) < abs(other - float(rae)):
                    _set(product, key, round(scaled, 4))
                    changed = True
    return changed


def fix_measures(product: dict) -> bool:
    """Снять «1 шт.»/отходы с рецептурных блюд, вернуть канонические меры."""
    code = product["code"]
    changed = False
    if RECIPE_NO.search(product["name"]):
        before = len(product["measures"])
        product["measures"] = [
            m for m in product["measures"]
            if not (m["name"].startswith("1 шт.") or "1 шт." in m["name"])]
        changed |= len(product["measures"]) != before
        if product.get("piece_g"):
            product["piece_g"] = []
            changed = True
        if product.get("waste_pct") is not None:
            product["waste_pct"] = None
            changed = True

    if code in BASE_WASTE and product.get("waste_pct") != BASE_WASTE[code]:
        product["waste_pct"] = BASE_WASTE[code]
        changed = True
    # Таблица 11 (напитки) — не сырьё: несъедобной части у напитков нет,
    # у вин и вовсе нет очистки (дефект L5).
    if code.startswith("11.") and product.get("waste_pct") is not None:
        product["waste_pct"] = None
        changed = True
    needed = BASE_PIECES.get(code) or BASE_MEASURES.get(code) or []
    if needed:
        names = {m["name"] for m in product["measures"]}
        add = [dict(m) for m in needed if m["name"] not in names]
        if add:
            product["measures"] = add + product["measures"]
            changed = True
    # Дефект D2: у жидкости группы 11 мер не было вовсе (приложение книги их
    # не покрывает), поэтому снятие «1 шт.» не должно оставить продукт без
    # мер. Ставим стандартные стаканы и ложки.
    if (not product.get("measures")
            and _is_no_piece_product(product)
            and code.startswith(NO_PIECE_GROUP_PREFIXES)):
        product["measures"] = _liquid_measures(code, product.get("name") or "")
        changed = True
    if code in BASE_PIECES and product.get("piece_g") != \
            [m["grams"] for m in BASE_PIECES[code]]:
        product["piece_g"] = [m["grams"] for m in BASE_PIECES[code]]
        changed = True
    if fix_measure_list(product):
        changed = True
    return changed


def polish_payload(payload: dict) -> dict[str, int]:
    """Исправить все продукты, вернуть счётчики изменений по группам."""
    stats = {"portion_rows": 0, "p142": 0, "names": 0, "measures": 0,
             "columns": 0, "values": 0}
    for product in payload["products"]:
        product.setdefault("synonyms", [])
        # порядок важен: меры зависят от итогового названия, а сдвиг
        # столбцов — от исходной (до деления) строки правой страницы
        if fix_columns(product):
            stats["columns"] += 1
        if clean_values(product):
            stats["values"] += 1
        if fix_portion_row(product):
            stats["portion_rows"] += 1
        if fix_p142(product):
            stats["p142"] += 1
        # повторный проход по значениям: fix_p142 переписывает строку правой
        # страницы для p116, и в неё снова попадает «хвост» РЭ
        if clean_values(product):
            stats["values"] += 1
        if fix_name(product):
            stats["names"] += 1
        if fix_measures(product):
            stats["measures"] += 1
    return stats


# Пары продуктов, у которых совпадение правой строки — свойство самой книги,
# а не след сдвига кодов: яйцо/яйцо отварное/меланж считаются по одинаковому
# составу, а варенец и простокваша 2,5 % — по одному нормативу.
SAME_ROW_ALLOWED = {
    frozenset({"2.1.1", "2.1.2"}),
    frozenset({"2.1.2", "2.2.1"}),
    frozenset({"1.2.2.1", "1.2.2.11"}),
}


def check(payload: dict) -> list[str]:
    """Инварианты после правки. Возвращает список нарушений."""
    problems: list[str] = []
    seen_right: dict[tuple, str] = {}
    for product in payload["products"]:
        code = product["code"]
        values = _values(product)
        mass = sum(values.get(k, 0.0) for k in
                   ("water", "protein", "fat", "carbs", "fiber",
                    "organic_acids", "ash"))
        if not any(k in values for k in ("water", "protein", "fat", "carbs")):
            continue
        # строка 100 г обязана собираться в 100 г, кроме алкоголя (табл. 11)
        if not code.startswith("11.") and mass and not 90.0 <= mass <= 110.0:
            problems.append(f"{code}: масса {mass:.1f} г на 100 г")
        name = product["name"]
        if TECH_PREFIX.match(name):
            problems.append(f"{code}: остался префикс раздела «{name}»")
        # ---- инварианты витаминов (C3, C4) ---------------------------
        # Ни у одного продукта табл. 1, 5, 10 витамин C или ниациновый
        # эквивалент не может совпадать с ЭЦ: это след сдвига последнего
        # столбца правой страницы.
        if code.startswith(VITAMIN_SHIFT_TABLES):
            kcal_v = values.get("energy_kcal")
            if kcal_v and float(kcal_v) > 3:
                for key in ("vitamin_c", "niacin_equivalent"):
                    got = values.get(key)
                    if got is not None and float(got) == float(kcal_v):
                        problems.append(
                            f"{code}: {key}={got:g} совпал с ЭЦ {kcal_v:g} "
                            f"(сдвиг последнего столбца)")
        # В таблице 5 (жиры и масла) C и НЭ практически нулевые.
        if code.startswith("5."):
            for key, limit in (("vitamin_c", TABLE5_VIT_C_MAX),
                               ("niacin_equivalent", TABLE5_NIAEQ_MAX)):
                got = values.get(key)
                if got is not None and float(got) > limit:
                    problems.append(
                        f"{code}: {key}={got:g} мг > {limit:g} мг в таблице 5")
        if RECIPE_NO.search(name) and any(
                "1 шт." in m["name"] for m in product["measures"]):
            problems.append(f"{code}: у рецептурного блюда мера «1 шт.»")
        # ЭЦ книги должна согласовываться с БЖУ (4/9/4 + спирт + РПВ).
        # Пищевые волокна и полиолы в таблице не входят в «У», но в ЭЦ
        # учтены: «Пектин (в т.ч. РПВ – 69,9)» — 200 ккал при 51 ккал по БЖУ.
        kcal = values.get("energy_kcal")
        base = (4.0 * values.get("protein", 0.0)
                + 9.0 * values.get("fat", 0.0)
                + 4.0 * values.get("carbs", 0.0)
                + 7.0 * values.get("alcohol", 0.0))
        extended = base + 4.0 * values.get("fiber", 0.0)
        if kcal and max(base, extended) > 0 and not any(
                0.45 <= kcal / reference <= 2.2
                for reference in (base, extended) if reference > 0):
            problems.append(
                f"{code}: ЭЦ {kcal:g} ккал против БЖУ {base:.0f} "
                f"(похоже, взята строка соседнего продукта)")
        # Два изделия одной таблицы не должны получить полностью идентичную
        # строку правой части — это след сдвига кодов на правой странице
        # (см. P116_REGROUP: «Булочка» и «Булка» делили одну строку).
        # Совпадение ЭЦ и Na у разных сортов одного продукта — нормально,
        # поэтому сравнивается вся строка целиком.
        row = tuple(values.get(key) for key in CANON_RIGHT)
        table = code.split(".")[0]
        if kcal and sum(1 for v in row if v) >= len(CANON_RIGHT) - 2:
            other = seen_right.get((table, row))
            if other and frozenset({code, other}) not in SAME_ROW_ALLOWED:
                problems.append(f"{code}: правая строка совпала с {other}")
            seen_right[(table, row)] = code
    return problems


def main() -> None:
    payload = json.loads(SRC.read_text(encoding="utf-8"))
    stats = polish_payload(payload)
    problems = check(payload)
    if problems:
        for text in problems[:30]:
            print("  !", text)
        raise SystemExit(f"полировка не сошлась: {len(problems)} нарушений")
    payload.setdefault("meta", {})["polished"] = stats
    SRC.write_text(json.dumps(payload, ensure_ascii=False, indent=1),
                   encoding="utf-8")
    print(f"продуктов: {len(payload['products'])}")
    for key, value in stats.items():
        print(f"  {key}: {value}")
    print(f"записан: {SRC}")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", line_buffering=True)
    main()
