def fix_name(product: dict) -> bool:
    """Убрать технический префикс раздела / собрать естественное название."""
    code = product["code"]
    name = product["name"]
    target = NAME_FIXES.get(code) or DUPLICATE_NAME_FIXES.get(code)
    if target is None:
        section = (product.get("section_path") or [""])[-1]
        generic = GENERIC_SECTIONS.get(section)
        if generic and ". " in name:
            _, kind = name.split(". ", 1)
            if not NO_GENERIC.match(kind.strip()):
                target = f"{generic} «{kind.strip()}»"
    if target is None or target == name:
        return False
    product["name"] = target
    for extra in SYNONYM_FIXES.get(code, []):
        if extra not in product["synonyms"]:
            product["synonyms"].append(extra)
    return True


