BLS_BISCUIT_CATEGORIES = ("BLS_B", "BLS_D", "BLS_S", "BLS_X", "BLS_Y")

# Дефект D15: «салат» — это прежде всего ЛИСТОВОЙ ОВОЩ («Салат айсберг
# сырой», «Полевой салат свежий», «Цикорный салат»), и в группе BLS_G
# голое `\bсалат\b` ошибочно делало его блюдом. В «овощных» группах BLS
# «салат» — растение; блюдо — только «салат с заправкой», «салат из … с
# майонезом/маслом/соусом/маринадом» или «картофельный/мясной/селёдочный
# салат». Критерий — НАЗВАНИЕ, а не группа: «Мясной салат с майонезом и
# огурцом» (W985000) — тоже блюдо, хотя группа W.
BLS_SALAD_DISH = re.compile(
    r"\bсалат[а-я]*\b[^,]{0,60}?(?:заправк|майонез|маслом|соус|маринад|сметан)"
    r"|\b(?:картофельн|мясн|селедочн|птичь|овощн|рыбн|яичн)[а-я]*\s+салат")

# BLS: копчёные/вяленые/солёные мясные и рыбные деликатесы — ингредиенты для
# рецептов и нарезки (`is_dish = 0`), как в книге, где все колбасы, ветчина и
# копчёности — сырьё. Ловятся только формы со стадией обработки («копчёный/
# копчёная/копчение», «солёный/солёная/соление»): прилагательное стоит перед
# существительным («Рыба копчёная»), а существительные «Копчение»,
# «Зельц», «Корейка» — нет. Исключение — если продукт термически доведён
# («варёно-копчёная», «копчёная, отварная»); такие остаются блюдами.
BLS_SMOKED_SALTED = re.compile(r"копчен[а-я]*|копчени[а-я]*|солен[а-я]*")

# BLS: категории-«гастрономия» — колбасы, ветчина, сосиски, шпик/бекон/
# грудинка. Это ровно те продукты, которые повар кладёт в рецепт.
BLS_GASTRONOMY_CATEGORIES = ("BLS_W",)

# Стандартные кулинарные меры для питьевого коровьего молока (стаканы и ложки).
MILK_MEASURES = (
    ("стакан 250 мл", 250.0),
    ("стакан 200 мл", 200.0),
    ("столовая ложка", 20.0),
    ("чайная ложка", 5.0),
)
SKURIKHIN_MILK_CODES = {
    "1.1.1.1", "1.1.1.2", "1.1.1.3",
    "1.2.1.1", "1.2.1.2", "1.2.1.3", "1.2.1.4", "1.2.1.5",
    "1.3.1.1", "1.3.1.2", "1.3.1.3", "1.3.1.4", "1.3.1.5",
}

# Готовые кулинарные изделия из колбас/ветчин (жареные, запечённые, на гриле, в тесте).
BLS_W_DISH = re.compile(
    r"жарен|обжарен|запеч|запек|(?<!для )грил|в тесте|в кляре|пирог|галантин|террин|отварн",
    re.I)
BLS_W_RAW_EXCEPTION = re.compile(
    r"для жареных колбасок|для гриля|для жарки",
    re.I)

# BLS (прочие категории): блюда и гарниры, которые не сырьё.
#
# Важно: прилагательное стоит ПЕРЕД существительным («Гречка варёная»,
# «Хлеб, поджаренный без жира»), творительный падеж — «Хлеб, поджаренный
# с жиром». Поэтому ловятся именно формы причастий («-ечён», «-еный»,
# «-ёный»), а слова вроде «мята свежая» или «Пшеница цельным зерном» — нет.
# Название приходит через `_norm_name`, где «ё» уже заменено на «е», поэтому
# шаблон написан в «е»-форме: `варен`/`тушен`/`запеч`/`запек`.
# Иначе «Гречка варёная» → «гречка вареная» не совпадала ни с `варён`, ни с
# `варенн` и оставалась сырьём (и тогда «гречка» вела к варёной крупе).
#
# Дефект D15: отсюда убран корень `печен` (см. `BLS_BAKED_FORMS` —
# «печень» ≠ «печёный») и `печенье` (см. `BLS_BISCUIT_FORMS`), а `салат`
# заменён на `BLS_SALAD_DISH`.
BLS_DISH_MARKERS = re.compile(
    # варёный / жареный / тушёный / запечённый / припущенный / пассированный / на пару / гриль
    r"варен|отвар"
    r"|жарен|обжарен|поджарен"
    r"|тушен"
    r"|запеч|запек"
    r"|припущен|пассирован"
    r"|на пару"
    r"|(?<!для )грил"
    r"|\bсуп\b|суп[- ]пюре|бульон|пудинг|запеканка|гратен"
    r"|винегрет|соус по рецепт|заправк"
    r"|\bторт|пирог|пирожн|вафл"
    # «Каша» — но не «Кашалот»/«Каштановый»: нужна граница слова
    r"|\bкаша\b|\bпюре\b"
    r"|котлет|фельдшен|\bгарнир\b"
    r"|оладь|драник|крокет|ньокки|клецк|равиоли|паста для бутерброд",
    re.I)


def _norm_name(text: str) -> str:
    return (text or "").lower().replace("ё", "е").strip()


def is_dish(item: dict, source: str, category_code: str | None = None) -> bool:
    """Готовое блюдо ли это (этап 6).

    Скурихин: ссылка на Сборник рецептур, подраздел «Кулинарные изделия» /
    «Бутерброды» или явный маркер в начале названия. BLS: группы BLS_X
    («Готовые блюда») и BLS_Y («Сложные блюда, супы») целиком, а в прочих
    группах — по морфологии названия (отварное, жареное, суп, торт…).

    Порядок разбора названия в прочих группах BLS (первое совпадение решает):
     1. явное сырьё: «сырой/свежий» или «замороженный» без термической
        готовки — `is_dish = 0` (`BLS_RAW_MARKERS`, `BLS_FROZEN_MARKER`);
     2. группа `BLS_W` — `is_dish = 0` (`BLS_GASTRONOMY_CATEGORIES`);
     3. копчёное/солёное без «варёного/жареного» — `is_dish = 0`
        (`BLS_SMOKED_SALTED`);
     4. «печенье» в кондитерских группах и причастие «печёный» —
        `is_dish = 1` (`BLS_BISCUIT_FORMS`, `BLS_BAKED_FORMS`);
     5. «салат с заправкой» / «картофельный салат» — `is_dish = 1`,
        голое «салат» — нет (`BLS_SALAD_DISH`);
     6. общие маркеры блюд — `BLS_DISH_MARKERS`.
    """
    if source == "supplement":
        return False
    name = _norm_name(item.get("name"))
    if not name:
        return False
    if source == "skurikhin":
        # мука и листовой салат из «Кулинарных изделий» — всё-таки сырьё
        if any(_norm_name(raw) == name for raw in SKURIKHIN_INGREDIENT_NAMES):
            return False
        if RECIPE_REF.search(name):
            return True
        sections = [_norm_name(s) for s in (item.get("section_path") or [])]
        if any(word in section
               for section in sections
               for word in SKURIKHIN_DISH_SECTIONS):
            return True
        return any(name.startswith(_norm_name(prefix))
                   for prefix in SKURIKHIN_DISH_PREFIXES)
    if source == "bls":
        if category_code in BLS_DISH_CATEGORIES:
            return True
        category = category_code or ""
        cooked = bool(BLS_COOKED_MARKERS.search(name))
        # «Варёный сыр» — сыр, а не «сырой продукт»; «сыворотка» — фракция
        state = BLS_NOT_A_STATE.sub(" ", name)
        biscuit = (bool(BLS_BISCUIT_FORMS.search(name))
                   and category in BLS_BISCUIT_CATEGORIES)
        baked = bool(BLS_BAKED_FORMS.search(name))
        # 1. явное сырьё: «печень сырая», «Ньокки замороженные» — ингредиент
        if (BLS_RAW_MARKERS.search(state) or BLS_FROZEN_MARKER.search(name)) \
                and not cooked and not biscuit and not baked:
            return False
        # 2. гастрономия группы W (колбасы, ветчина, сосиски, шпик)
        if category in BLS_GASTRONOMY_CATEGORIES:
            if BLS_W_DISH.search(name) and not (
                BLS_W_RAW_EXCEPTION.search(name) and not re.search(r"обжарен|запеч|жарен.*без жира|на гриле", name)
            ):
                return True
            return False
        # 3. копчёности/солёности без термической готовки: «Лосось копчёный»,
        #    «Вырезка сырокопчёная» — ингредиенты; «варёно-копчёная» — блюдо
        if BLS_SMOKED_SALTED.search(name) and not cooked:
            return False
        # 4. «печенье» — кондитерка только в кондитерских группах;
        #    «печень» матчится лишь `BLS_BAKED_FORMS` («печёная …»)
        if biscuit or baked:
            return True
        # 5. салат: блюдо — только с заправкой/именем блюда
        if BLS_SALAD_DISH.search(name):
            return True
        stripped = BLS_SALAD_DISH.sub(" ", name)
        # 6. общие маркеры блюд
        return bool(BLS_DISH_MARKERS.search(stripped))
    return False


