def apply_yo_disambiguation(products: list[dict]) -> None:
    """Развести имена, различающиеся только «е»/«ё» (дефект D6).

    Дополнительно — общая страховка: если после уточнения всё ещё есть
    коллизия по `.lower().replace('ё', 'е')` между BLS и книгой, BLS-запись
    получает «(BLS)».
    """
    by_code = {item["code"]: item for item in products}
    for code, name in YO_DISAMBIGUATION.items():
        if code in by_code:
            by_code[code]["name"] = name
    for code, name in BLS_NAME_FIXES.items():
        if code in by_code:
            by_code[code]["name"] = name
    seen: dict[str, str] = {}
    for item in products:
        key = (item.get("name") or "").lower().replace("ё", "е")
        other = seen.setdefault(key, item["code"])
        if other != item["code"] and item.get("code", "").startswith("F"):
            # BLS уступает книге: дописываем уточнение источника
            if not item["name"].endswith("(BLS)"):
                item["name"] = f"{item['name']} (BLS)"


