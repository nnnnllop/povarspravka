def normalize(text: str) -> str:
    """Та же нормализация, что `ProductRepository._normalizeQuery` в Dart."""
    low = (text or "").lower().replace("ё", "е")
    cleaned = "".join(ch if (ch.isalnum() or ch.isspace()) else " "
                      for ch in low)
    return " ".join(cleaned.split())


def nutrient_value(item: dict, key: str) -> float | None:
    cell = (item.get("nutrients") or {}).get(key)
    if cell is None:
        return None
    # «Дополнения» (SUPPLEMENTS) задают значения числом, источник — структурой
    # {"value": …, "unit": …}; поддерживаются оба вида.
    if not isinstance(cell, dict):
        value = round(float(cell), 4)
    else:
        value = cell.get("value")
        if value is None:
            return None
        factor = UNIT_FACTORS.get(key, {}).get(
            str(cell.get("unit") or "").lower())
        value = round(float(value) * (factor or 1.0), 4)
    # Дефект D7: у четырёх минеральных вод BLS вода 100,2…100,6 г на 100 г —
    # физически невозможно. Зажимаем, чтобы сумма не превышала 100 г.
    if key == "water":
        value = min(value, 100.0)
    return value


def load_json(path: Path) -> list[dict]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    products = payload.get("products") if isinstance(payload, dict) else payload
    if not products:
        raise SystemExit(f"нет продуктов в {path}")
    return products


def reconcile_vitamin_a(codes: dict[str, float], source: str) -> float | None:
    """Привести РЭ к минимуму, который допускают его источники (дефект D16).

    В BLS 4.0 столбец `VITA` (РЭ) округлён до ЦЕЛЫХ мкг, а `RETOL` задан с
    десятыми долями мкг. Из-за округления получались строки с `RETOL > VITA`
    (`W255700`: 1530,1 против 1530,0; `W110000`: 8,1 против 8,0; `S581900`:
    0,7 против 0), а у строк с малым `CARTB` (1…3 мкг при РЭ = 0) сумма
    `RETOL + CARTB/12` превышала РЭ на 0,08…0,33 мкг. То же в книге, где РЭ
    и `RETOL` округлены независимо.

    Физический минимум РЭ — это сумма по формуле самого источника:
      * BLS: `РЭ = ретинол + β-каротин/12` (мкг/100 г);
      * Скурихин: `РЭ >= ретинол` (каротиноиды только увеличивают РЭ).
    Если записанное РЭ меньше этого минимума, оно округлялось вниз — поднимаем
    его до минимума. Значение выше минимума НЕ трогаем: добавка объясняется
    прочими каротиноидами (α-каротин, криптоксантин).

    Возвращает новое значение `VITA_RAE` или `None`, если менять нечего.
    Порог 0,005 — тот же, что у `test_no_float_noise_in_nutrients`: ниже него
    значение в `nutrient_value` не пишется вовсе (шум округления).
    """
    retinol = codes.get("RETOL", 0.0)
    if source == "bls":
        minimum = round(retinol + codes.get("CARTB", 0.0) / 12.0, 4)
    else:
        minimum = round(retinol, 4)
    if minimum < 0.005:
        return None
    if codes.get("VITA_RAE", 0.0) >= minimum:
        return None
    return minimum


def build_rows() -> tuple[list[tuple], list[tuple]]:
    """Собрать группы и продукты из обоих источников."""
    groups: list[tuple] = [
        (gid, str(gid), name) for gid, name in sorted(SKURIKHIN_GROUPS.items())]

    skurikhin = load_json(SKURIKHIN_JSON)
    bls = load_json(BLS_JSON)
    # D6: развести имена, различающиеся только «е»/«ё»
    apply_yo_disambiguation(skurikhin + bls)

    # BLS: группа на каждую букву кода, в порядке букв (101…).
    letters: dict[str, str] = {}
    for item in bls:
        letter = (item.get("category_letter") or item["code"][0]).upper()
        letters.setdefault(letter, item.get("category") or letter)
    bls_group: dict[str, int] = {}
    for offset, letter in enumerate(sorted(letters)):
        gid = GROUP_ID_BASE + offset
        bls_group[letter] = gid
        groups.append((gid, f"BLS_{letter}", letters[letter]))

    rows: list[tuple] = []
    for index, item in enumerate(skurikhin):
        table = int(item["code"].split(".")[0])
        rows.append(_product_row(item, index + 1, table, "skurikhin",
                                 (item.get("source") or {}).get("page_left")))
    for index, item in enumerate(bls):
        letter = (item.get("category_letter") or item["code"][0]).upper()
        rows.append(_product_row(item, BLS_ID_BASE + index,
                                 bls_group[letter], "bls", None,
                                 f"BLS_{letter}"))
    # Приправы и питьевая вода: их нет ни в книге, ни в BLS, но без них не
    # собрать рецепт (дефект M5). Группа 12 — «вспомогательные продукты».
    # Специи — всегда сырьё (`is_dish = 0`).
    for offset, item in enumerate(SUPPLEMENTS):
        item = _balance_supplement(item)
        rows.append(_product_row(item, SUPPLEMENT_ID_BASE + offset, 12,
                                 "supplement", None))
    return groups, rows


def _balance_supplement(item: dict) -> dict:
    """Подогнать углеводы пряности так, чтобы масса давала ровно 100 г.

    Значения из USDA округлены до сотых, поэтому сумма компонентов
    уезжает на ±0,02 г. Раньше остаток «съедали» отрицательные
    органические кислоты (−0,01 г) — величина, которой не бывает.
    Теперь остаток уходит в углеводы (единственный «по разности»
    компонент), а органические кислоты остаются нулём.
    """
    if item.get("source") != "supplement" and "nutrients" not in item:
        return item
    nutrients = item.get("nutrients") or {}
    if "carbs" not in nutrients:
        return item
    parts = ("water", "protein", "fat", "carbs", "fiber", "organic_acids", "ash")
    total = sum(float(nutrients.get(key) or 0.0) for key in parts)
    if abs(total - 100.0) < 1e-9:
        return item
    balanced = dict(item)
    fixed = dict(nutrients)
    fixed["carbs"] = round(float(nutrients["carbs"]) + (100.0 - total), 2)
    balanced["nutrients"] = fixed
    return balanced


def _product_row(item: dict, pid: int, group_id: int, source: str,
                 page_num: int | None, category_code: str | None = None
                 ) -> tuple:
    name = (item.get("name") or "").strip()
    macros = [nutrient_value(item, key) or 0.0 for key in MACRO_COLUMNS]
    assert len(macros) == len(PRODUCT_MACROS), "MACRO_COLUMNS ≠ PRODUCT_MACROS"
    # Аудит №9: если калорийность равна 0 при наличии БЖУ (сок томатный, кофе черный
    # в Скурихине), используем книжную расчетную калорийность energy_calc_kcal.
    if macros[3] <= 0.0:
        calc_kcal = item.get("energy_calc_kcal")
        if calc_kcal is not None and float(calc_kcal) > 0:
            macros[3] = round(float(calc_kcal), 1)
        else:
            base_kcal = 4.0 * macros[0] + 9.0 * macros[1] + 4.0 * macros[2]
            if base_kcal > 1.0:
                macros[3] = round(base_kcal, 1)
    waste = item.get("waste_pct") if source == "skurikhin" else None
    return (
        pid,
        item["code"],
        name,
        normalize(name),
        group_id,
        source,
        page_num,
        float(waste) if waste is not None else 0.0,
        *macros,
        1 if is_dish(item, source, category_code) else 0,
    )


def build_database(path: Path) -> dict[str, int]:
    """Создать базу с нуля; вернуть статистику."""
    path.parent.mkdir(parents=True, exist_ok=True)
    for suffix in ("", "-wal", "-shm"):
        stale = Path(str(path) + suffix)
        if stale.exists():
            stale.unlink()

    groups, products = build_rows()
    skurikhin = load_json(SKURIKHIN_JSON)
    bls = load_json(BLS_JSON)
    by_code = {item["code"]: item for item in skurikhin + bls + SUPPLEMENTS}

    unknown = sorted(set(CULINARY_SYNONYMS) - set(by_code))
    if unknown:
        raise SystemExit(f"кулинарные синонимы ссылаются на несуществующие "
                         f"коды: {unknown}")

    stats = {"food_group": 0, "product": 0, "nutrient_value": 0,
             "measure": 0, "synonym": 0, "product_fts": 0}

    conn = sqlite3.connect(path)
    try:
        conn.executescript("PRAGMA journal_mode = DELETE;"
                           "PRAGMA foreign_keys = OFF;")
        conn.executescript(SCHEMA)
        conn.executemany("INSERT INTO food_group VALUES (?, ?, ?)", groups)
        stats["food_group"] = len(groups)
        conn.executemany(
            "INSERT INTO product VALUES (" + ", ".join("?" * 23) + ")",
            products)
        stats["product"] = len(products)

        measures, nutrients, synonyms, fts = [], [], [], []
        for row in products:
            pid, code = row[0], row[1]
            item = by_code[code]
            seen_measure: set[str] = set()
            for measure in item.get("measures") or []:
                grams = measure.get("grams")
                if grams is None or float(grams) <= 0:
                    continue
                name = str(measure.get("name") or "порция").strip()
                # UNIQUE(product_id, name): одинаковые подписи не пишем дважды
                if name in seen_measure:
                    continue
                seen_measure.add(name)
                measures.append((pid, name, float(grams)))
            if code in SKURIKHIN_MILK_CODES:
                for m_name, m_grams in MILK_MEASURES:
                    if m_name not in seen_measure:
                        seen_measure.add(m_name)
                        measures.append((pid, m_name, m_grams))
            # Дефект D16: `retinol` (BLS) и `vitamin_a` (книга) — одна и та же
            # величина в product.dart (`RETOL`), поэтому ключи сводятся в dict:
            # первый непустой побеждает, дубль в nutrient_value не появляется.
            codes: dict[str, float] = {}
            for key, nutrient_code in NUTRIENT_CODES.items():
                value = nutrient_value(item, key)
                if value is None or value <= 0:
                    continue
                codes.setdefault(nutrient_code, value)
            # Дефект D16: у продуктов с ретинолом и/или β-каротином записанное
            # РЭ может быть МЕНЬШЕ физически возможного минимума — BLS
            # округляет `VITA` до целых мкг, а книга округляет РЭ и ретинол
            # независимо. Поднимаем РЭ до минимума, чтобы инвариант
            # `RETOL <= VITA_RAE` и `RETOL + CARTB/12 <= VITA_RAE` выполнялся
            # во ВСЕЙ базе, а не только на глаз.
            if "RETOL" in codes or "CARTB" in codes:
                fixed = reconcile_vitamin_a(codes, row[5])
                if fixed is not None:
                    codes["VITA_RAE"] = fixed
            for nutrient_code, value in codes.items():
                nutrients.append((pid, nutrient_code, value))

            names = []
            for text in list(item.get("synonyms") or []) + \
                    CULINARY_SYNONYMS.get(code, []):
                text = (text or "").strip()
                norm = normalize(text)
                if not text or not norm:
                    continue
                if text.lower() == row[2].lower():
                    continue
                if norm not in names:
                    names.append(norm)
                    synonyms.append((pid, text, norm))

            fts_name = row[2]
            fts_norm = " ".join([row[3]] + names).strip()
            fts.append((pid, fts_name, fts_norm))

        conn.executemany(
            "INSERT INTO measure (product_id, name, grams) VALUES (?, ?, ?)",
            measures)
        conn.executemany(
            "INSERT INTO nutrient_value (product_id, nutrient_code, value) "
            "VALUES (?, ?, ?)", nutrients)
        conn.executemany(
            "INSERT INTO synonym (product_id, synonym, synonym_norm) "
            "VALUES (?, ?, ?)", synonyms)
        conn.executemany(
            "INSERT INTO product_fts (product_id, name, name_norm) "
            "VALUES (?, ?, ?)", fts)
        stats["measure"] = len(measures)
        stats["nutrient_value"] = len(nutrients)
        stats["synonym"] = len(synonyms)
        stats["product_fts"] = len(fts)

        conn.execute("INSERT INTO product_fts(product_fts) VALUES('optimize')")
        # Версия схемы для приложения: `_schemaVersionPrefix = 'v5'` в
        # `product_repository.dart` сверяется с CRC ассета, а `user_version`
        # позволяет отличить базу v4 (без `product.is_dish`) от v5.
        conn.execute("PRAGMA user_version = 5")
        conn.commit()
        problem = conn.execute("PRAGMA integrity_check").fetchone()[0]
        if problem != "ok":
            raise SystemExit(f"integrity_check: {problem}")
    finally:
        conn.close()

    # Один компактный файл без -wal/-shm хвостов.
    conn = sqlite3.connect(path, isolation_level=None)
    try:
        conn.execute("PRAGMA journal_mode = DELETE")
        conn.execute("VACUUM")
    finally:
        conn.close()
    return stats


def collect_stats(path: Path) -> dict[str, object]:
    conn = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    try:
        info: dict[str, object] = {}
        for table in ("food_group", "product", "nutrient_value", "measure",
                      "synonym", "product_fts"):
            info[table] = conn.execute(
                f"SELECT COUNT(*) FROM {table}").fetchone()[0]
        info["skurikhin"] = conn.execute(
            "SELECT COUNT(*) FROM product WHERE source='skurikhin'"
        ).fetchone()[0]
        info["bls"] = conn.execute(
            "SELECT COUNT(*) FROM product WHERE source='bls'").fetchone()[0]
        info["skurikhin_id_range"] = conn.execute(
            "SELECT MIN(id), MAX(id) FROM product WHERE source='skurikhin'"
        ).fetchone()
        info["bls_id_range"] = conn.execute(
            "SELECT MIN(id), MAX(id) FROM product WHERE source='bls'"
        ).fetchone()
        info["bls_page_null"] = conn.execute(
            "SELECT COUNT(*) FROM product WHERE source='bls' AND page_num IS "
            "NULL").fetchone()[0]
        info["journal_mode"] = conn.execute(
            "PRAGMA journal_mode").fetchone()[0]
        info["integrity_check"] = conn.execute(
            "PRAGMA integrity_check").fetchone()[0]
        return info
    finally:
        conn.close()


def verify(path: Path) -> list[str]:
    """Инварианты боевой базы; пустой список — всё в порядке."""
    problems: list[str] = []
    info = collect_stats(path)
    for table in ("food_group", "product", "nutrient_value", "measure",
                  "synonym", "product_fts"):
        if not info[table]:
            problems.append(f"пустая таблица {table}")
    if info["integrity_check"] != "ok":
        problems.append(f"integrity_check = {info['integrity_check']}")
    if str(info["journal_mode"]).lower() != "delete":
        problems.append(f"journal_mode = {info['journal_mode']}")
    if info["bls_page_null"] != info["bls"]:
        problems.append("у части продуктов BLS задан page_num")

    conn = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    try:
        # Поиск идёт через `JOIN product p ON p.id = CAST(f.product_id AS
        # INTEGER)` (см. ProductRepository), поэтому важен product_id, а не
        # rowid виртуальной таблицы.
        missing = conn.execute(
            "SELECT COUNT(*) FROM product p WHERE NOT EXISTS ("
            "SELECT 1 FROM product_fts f "
            "WHERE CAST(f.product_id AS INTEGER) = p.id)").fetchone()[0]
        if missing:
            problems.append(f"{missing} продуктов без строки FTS")
        orphan = conn.execute(
            "SELECT COUNT(*) FROM product_fts f WHERE NOT EXISTS ("
            "SELECT 1 FROM product p "
            "WHERE p.id = CAST(f.product_id AS INTEGER))").fetchone()[0]
        if orphan:
            problems.append(f"product_fts: {orphan} строк без продукта")
        # группы 1..12 — Скурихин, 101.. — BLS
        wrong = conn.execute(
            "SELECT COUNT(*) FROM product WHERE "
            "(source='skurikhin' AND (group_id < 1 OR group_id > 12)) OR "
            "(source='bls' AND group_id < 101)").fetchone()[0]
        if wrong:
            problems.append(f"{wrong} продуктов в чужой группе")
        # единицы: йод — мкг, каротин — мкг (в данных уже мкг)
        huge = conn.execute(
            "SELECT COUNT(*) FROM nutrient_value WHERE nutrient_code='I' "
            "AND value > 10000").fetchone()[0]
        if huge:
            problems.append(f"{huge} значений йода неправдоподобны (мг/мкг)")
        for column in ("protein", "fat", "carbs", "waste_pct"):
            over = conn.execute(
                f"SELECT COUNT(*) FROM product WHERE {column} < 0 OR "
                f"{column} > 100").fetchone()[0]
            if over:
                problems.append(f"product.{column}: {over} вне 0…100")
        banned = conn.execute(
            "SELECT COUNT(*) FROM product WHERE name LIKE '%USA%' OR "
            "name LIKE '%USDA%'").fetchone()[0]
        if banned:
            problems.append(f"{banned} названий с USDA")
        # Дефект D16: ретинол не может быть больше РЭ. BLS округляет `VITA`
        # до целых мкг, а `RETOL` несёт десятые доли, поэтому без сверки
        # (см. `reconcile_vitamin_a`) в базе появлялись строки «1530,1 мкг
        # ретинола при 1530,0 мкг РЭ» — физически невозможно.
        over_retinol = conn.execute(
            "SELECT COUNT(*) FROM product p "
            "JOIN nutrient_value r ON r.product_id = p.id "
            "AND r.nutrient_code = 'RETOL' "
            "LEFT JOIN nutrient_value v ON v.product_id = p.id "
            "AND v.nutrient_code = 'VITA_RAE' "
            "WHERE r.value > COALESCE(v.value, 0.0) + 1e-9").fetchone()[0]
        if over_retinol:
            problems.append(
                f"RETOL > VITA_RAE у {over_retinol} продуктов (дефект D16)")
        # и формула BLS: РЭ = ретинол + β-каротин/12 (допуск на округление
        # до десятых — 0,01 мкг).
        over_carotene = conn.execute(
            "SELECT COUNT(*) FROM product p "
            "LEFT JOIN nutrient_value r ON r.product_id = p.id "
            "AND r.nutrient_code = 'RETOL' "
            "LEFT JOIN nutrient_value b ON b.product_id = p.id "
            "AND b.nutrient_code = 'CARTB' "
            "LEFT JOIN nutrient_value v ON v.product_id = p.id "
            "AND v.nutrient_code = 'VITA_RAE' "
            "WHERE p.source = 'bls' "
            "AND COALESCE(r.value, 0.0) + COALESCE(b.value, 0.0) / 12.0 "
            "> COALESCE(v.value, 0.0) + 0.01").fetchone()[0]
        if over_carotene:
            problems.append(
                f"BLS: RETOL + CARTB/12 > VITA_RAE + 0,01 у {over_carotene} "
                f"продуктов (дефект D16)")
        # контрольные поиски из отчёта
        for query, expected_min in (("картошка", 1), ("гречка", 1),
                                    ("свекла", 1), ("молоко", 1),
                                    ("яйцо", 1), ("сметана", 1)):
            match = " ".join(f'"{token}"*' for token in query.split())
            found = conn.execute(
                "SELECT COUNT(*) FROM product_fts WHERE product_fts MATCH ?",
                (match,)).fetchone()[0]
            if found < expected_min:
                problems.append(f"поиск «{query}» ничего не нашёл")
    finally:
        conn.close()
    return problems


def _fts_tokens(text: str) -> list[str]:
    """Токены FTS5 с усечённым окончанием и беглым гласным.

    FTS5-префикс `"сырок"*` НЕ находит «сырки»: у слова беглое гласное, и
    основа другая — «сырк». Из-за этого поиск «сырок» отдавал «Колбасу
    сырокопченую» вместо творожных сырков. Поэтому:
      * отбрасывается КОНЕЧНОЕ ОКОНЧАНИЕ — гласные/«й»/«ь» подряд, пока в
        основе остаётся минимум 3 буквы («гречка» → «гречк»);
      * отбрасывается беглое гласное перед «к/ц» («сырок» → «сырк», и
        «сырок», «сырки» дают одну основу).
    Короткие токены (≤3) не трогаются, иначе «сыр» совпадёт с «сырок».

    Этап 6.6: окончание отсекается ЦИКЛОМ, а не одним символом. Раньше
    «куриный» → «курины» (в базе только «куриная»/«куриное»), «говяжий» →
    «говяжи» (в базе «говяжья»), «свиная» → «свина» (в базе «свиной»), и
    запрос «окорочок куриный» отдавал ПУСТО. Теперь прилагательные всех
    родов сходятся к одной основе: «куриный»/«куриная»/«куриное» → «курин»,
    «говяжий»/«говяжья»/«говяжье» → «говяж», «свиной»/«свиная» → «свин».
    """
    out: list[str] = []
    for token in normalize(text).split():
        if len(token) <= 3:
            out.append(token)
            continue
        # беглое гласное: «сырок» → «сырк», «платок» → «платк»
        if len(token) > 4 and token[-2] in "оеё" and token[-1] == "к":
            out.append(token[:-2] + "к")
            continue
        # окончание: «куриный» → «курин», «говяжья» → «говяж»
        while len(token) > 3 and token[-1] in "аеёиоуыэюяйь":
            token = token[:-1]
        out.append(token)
    return out


def search(path: Path, query: str, limit: int = 5,
           is_dish: bool | None = None) -> list[tuple]:
    """Контрольный FTS5-поиск так же, как в `ProductRepository`.

    Ранжирование (дефект H3): сначала продукты, где запрос — ЦЕЛОЕ слово,
    затем те, где он — начало слова, потом остальные совпадения; внутри
    каждой группы — продукты-ингредиенты раньше готовых блюд, Скурихин
    раньше BLS, затем bm25 и длина названия. Без этого «сыр» первым отдавал
    «Сырники» и «Сырки глазированные», а «печень» — «Печенье».

    `is_dish`: `False` — только сырьё/продукты, `True` — только готовые блюда,
    `None` — все (этап 6).
    """
    conn = sqlite3.connect(f"file:{path}?mode=ro", uri=True)
    try:
        tokens = _fts_tokens(query)
        if not tokens:
            return []
        clean = " ".join(normalize(query).split())
        # Две формы запроса:
        #   exact — как написано («сода» не цепляет «содержанием»);
        #   stem  — усечённая основа, чтобы дотянуться до других форм
        #           («сырок» → «сырки», «гречка» → «гречке»).
        # Складываем два ранжированных потока вручную: точная форма идёт
        # ПЕРВОЙ, усечённая добавляет то, что не нашлось. Одним запросом с
        # `OR` этого не сделать: bm25 перемешивает оба потока.
        #
        # Дефект D10: префикс «морс*» цепляет «морской» («Окунь морской»).
        # Поэтому для запросов длиной ≥ 4 в первом проходе ищется ЦЕЛОЕ
        # слово (без `*`), а префиксный проход по усечённой основе остаётся
        # вторым — он дотягивается до словоформ («сырок» → «сырки»).
        exact = " ".join(normalize(query).split())
        first_pass_exact = all(len(t) >= 4 for t in exact.split())
        match_exact = " ".join(
            f'"{t}"' if first_pass_exact else f'"{t}"*' for t in exact.split())
        match_stem = " ".join(f'"{token}"*' for token in tokens)
        dish_sql, dish_args = "", []
        if is_dish is not None:
            dish_sql = " AND p.is_dish = :dish "
            dish_args = [1 if is_dish else 0]
        sql = (
            "SELECT p.code, p.name, p.source FROM product_fts f "
            "JOIN product p ON p.id = CAST(f.product_id AS INTEGER) "
            "WHERE product_fts MATCH :m " + dish_sql +
            "ORDER BY "
            # Сырьё выше готовых блюд при прочих равных (этап 6): технолог
            # ищет ингредиент, а не «Гречневую кашу» и «Курицу жареную».
            "  p.is_dish ASC, "
            "  CASE "
            "    WHEN p.name_norm = :q THEN 0 "
            # ЦЕЛОЕ слово в названии.
            "    WHEN (' ' || p.name_norm || ' ') LIKE :word THEN 1 "
            # Слово НЕ в названии, но целиком в синониме: «сырок» →
            # «Сырки глазированные» (синоним «сырок»), а не «Колбаса
            # сырокопченая», где «сырок» лишь начало слова.
            "    WHEN (' ' || f.name_norm || ' ') LIKE :word THEN 2 "
            "    WHEN p.name_norm LIKE :starts THEN 3 "
            "    WHEN p.name_norm LIKE :inner THEN 4 "
            "    ELSE 5 END, "
            # Совпадение только по синониму слабее совпадения по названию.
            "  CASE WHEN p.name_norm LIKE :inner THEN 0 ELSE 1 END, "
            "  CASE WHEN p.source='skurikhin' THEN 0 ELSE 1 END, "
            "  bm25(product_fts, 10.0, 1.0), LENGTH(p.name) "
            "LIMIT :limit")
        params = {"q": clean, "starts": f"{clean} %", "word": f"% {clean} %",
                  "inner": f"%{clean}%", "limit": limit,
                  "dish": dish_args[0] if dish_args else None}
        rows = conn.execute(sql, {**params, "m": match_exact}).fetchall()
        have = {row[0] for row in rows}
        # второй проход: добираем прочие словоформы
        rows += [row for row in conn.execute(
            sql, {**params, "m": match_stem}).fetchall()
            if row[0] not in have]
        return rows[:limit]
    finally:
        conn.close()


QUERIES = ("картошка", "гречка", "свекла", "молоко 3.2", "семга", "рибай",
           "яйцо", "сметана 10")


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                       help="не собирать, только проверить готовую базу")
    parser.add_argument("--out", type=Path, default=OUT_DB)
    args = parser.parse_args(argv)

    if not args.check:
        stats = build_database(args.out)
        print(f"собрано: {args.out}")
        for key, value in stats.items():
            print(f"  {key}: {value}")
        MIRROR_DB.parent.mkdir(parents=True, exist_ok=True)
        MIRROR_DB.write_bytes(args.out.read_bytes())
        print(f"копия: {MIRROR_DB}")

    problems = verify(args.out)
    info = collect_stats(args.out)
    size_mb = args.out.stat().st_size / 1048576
    print(f"размер: {size_mb:.2f} МБ")
    print(f"Скурихин: {info['skurikhin']} (id {info['skurikhin_id_range']})")
    print(f"BLS: {info['bls']} (id {info['bls_id_range']})")
    print("контрольные поиски:")
    for query in QUERIES:
        hits = search(args.out, query)
        print(f"  «{query}»: {len(hits)}"
              + (f" — {hits[0][1]} [{hits[0][2]}]" if hits else " — пусто"))
    if problems:
        for text in problems:
            print("  !", text)
        raise SystemExit(f"проверка базы: {len(problems)} нарушений")
    print("проверка базы: OK")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", line_buffering=True)
    main()
